-- PostgreSQL's branch of migrations/0001-initial.sql (WP5.7 of
-- docs/PLAN.md, a spike): the same tables, columns and constraints, which
-- that file explains. A step's two files always make the same schema;
-- only what the two databases write differently differs:
--
--   * flags are BOOLEAN, where SQLite has an INTEGER checked to be 0 or 1;
--   * a grant has a rowid column, its place among the grants, which
--     SQLite's tables have without naming it: grants are read in the order
--     they were given (Wiki.Server.Storage.Entities).
--
-- Times stay text, as SQLite has them: a time is compared by equality with
-- every digit of its fraction of a second, which timestamptz (microseconds)
-- would not keep.

CREATE TABLE users (
  id           TEXT PRIMARY KEY NOT NULL,
  login        TEXT NOT NULL UNIQUE,
  display_name TEXT NOT NULL
);

CREATE TABLE groups (
  id   TEXT PRIMARY KEY NOT NULL,
  name TEXT NOT NULL
);

CREATE TABLE group_members (
  group_id TEXT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
  user_id  TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, user_id)
);

CREATE TABLE global_grants (
  rowid        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_kind TEXT NOT NULL CHECK (subject_kind IN ('user', 'group')),
  subject_id   TEXT NOT NULL,
  permission   TEXT NOT NULL CHECK (permission IN ('administer', 'create-spaces')),
  UNIQUE (subject_kind, subject_id, permission)
);

CREATE TABLE spaces (
  id             TEXT PRIMARY KEY NOT NULL,
  parent         TEXT REFERENCES spaces (id) ON DELETE CASCADE,
  name           TEXT NOT NULL,
  slug           TEXT NOT NULL,
  public         BOOLEAN NOT NULL,
  math_macros    TEXT NOT NULL,
  created_at     TEXT NOT NULL,
  position       INTEGER NOT NULL,
  subspace_order TEXT NOT NULL CHECK (subspace_order IN ('name', 'newest-first', 'oldest-first', 'by-hand')),
  page_order     TEXT NOT NULL CHECK (page_order IN ('name', 'newest-first', 'oldest-first', 'by-hand'))
);

CREATE UNIQUE INDEX spaces_sibling_slug ON spaces (coalesce(parent, ''), slug);

CREATE TABLE space_grants (
  rowid        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  space_id     TEXT NOT NULL REFERENCES spaces (id) ON DELETE CASCADE,
  subject_kind TEXT NOT NULL CHECK (subject_kind IN ('user', 'group')),
  subject_id   TEXT NOT NULL,
  permission   TEXT NOT NULL CHECK (permission IN ('view', 'edit', 'administer')),
  UNIQUE (space_id, subject_kind, subject_id, permission)
);

CREATE TABLE pages (
  id          TEXT PRIMARY KEY NOT NULL,
  space_id    TEXT NOT NULL REFERENCES spaces (id) ON DELETE CASCADE,
  parent      TEXT REFERENCES pages (id) ON DELETE CASCADE,
  title       TEXT NOT NULL,
  slug        TEXT NOT NULL,
  body        TEXT NOT NULL,
  created_at  TEXT NOT NULL,
  updated_at  TEXT NOT NULL,
  position    INTEGER NOT NULL,
  search_text TEXT NOT NULL
);

CREATE UNIQUE INDEX pages_sibling_slug ON pages (space_id, coalesce(parent, ''), slug);
CREATE INDEX pages_parent ON pages (parent);

CREATE TABLE page_versions (
  page_id    TEXT NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
  updated_at TEXT NOT NULL,
  title      TEXT NOT NULL,
  body       TEXT NOT NULL,
  author     TEXT,
  PRIMARY KEY (page_id, updated_at)
);

CREATE TABLE attachments (
  id         TEXT PRIMARY KEY NOT NULL,
  page_id    TEXT NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  media_type TEXT NOT NULL,
  size       BIGINT NOT NULL CHECK (size >= 0),
  url        TEXT,
  blob       TEXT,
  ordinal    INTEGER NOT NULL,
  CHECK ((url IS NULL) <> (blob IS NULL)),
  UNIQUE (page_id, name)
);

CREATE INDEX attachments_blob ON attachments (blob) WHERE blob IS NOT NULL;

CREATE TABLE drafts (
  page_id  TEXT NOT NULL REFERENCES pages (id) ON DELETE CASCADE,
  author   TEXT NOT NULL,
  title    TEXT NOT NULL,
  body     TEXT NOT NULL,
  base     TEXT NOT NULL,
  saved_at TEXT NOT NULL,
  PRIMARY KEY (page_id, author)
);
