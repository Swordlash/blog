-- A page's versions in time order, for a page of its history at a time
-- (WP5.16b of docs/PLAN.md, finding 9 of docs/scalability-audit.md).
--
-- A version's updated_at is the time as Wiki.Server.Storage.Rows.Stamp
-- writes it: ISO 8601 with as many digits of the fraction of a second as
-- needed, then Z. Ordered as text, a time with no fraction comes after
-- one in the same second with a fraction, since Z sorts after the dot.
-- Without the Z the text sorts in time order: the time with no fraction
-- is then a prefix of the other, and sorts first. A history lists its
-- versions by that text through this index, without reading and sorting
-- every version of the page.
CREATE INDEX page_versions_order ON page_versions (page_id, rtrim(updated_at, 'Z'));
